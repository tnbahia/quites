let labrego = false;

export const isLabrego = () => labrego;

export function setLabrego(on) {
  labrego = Boolean(on);
}

/** O texto pedido na versão ativa; as funções recebem os argumentos. */
export function t(key, ...args) {
  const value = (labrego ? LABREGO : NORMAL)[key];
  return typeof value === 'function' ? value(...args) : value;
}

/** Escreve na página os textos fixos do index.html (data-t, data-t-ph, data-t-label). */
export function applyStaticTexts(root = document) {
  for (const el of root.querySelectorAll('[data-t]')) el.textContent = t(el.dataset.t);
  for (const el of root.querySelectorAll('[data-t-ph]')) el.setAttribute('placeholder', t(el.dataset.tPh));
  for (const el of root.querySelectorAll('[data-t-label]')) el.setAttribute('aria-label', t(el.dataset.tLabel));
  (root.ownerDocument ?? root).title = t('title');
}
